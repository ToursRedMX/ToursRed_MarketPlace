import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source=fs.readFileSync(new URL('../src/lib/externalQrSession.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const token='ab'.repeat(32);
let clean;
const window={location:{hash:'#external-qr='+token+'&section=checkin',pathname:'/agency/agenda',search:'?tour=test'},history:{state:{},replaceState(_state,_title,url){clean=url;}}};
const context={exports:{},window,URLSearchParams};
vm.runInNewContext(compiled,context);
context.exports.captureExternalQr();
assert.equal(clean,'/agency/agenda?tour=test#section=checkin');
assert.equal(context.exports.pendingExternalQr(),token);
window.location.hash='#external-qr=invalid';
context.exports.captureExternalQr();
assert.equal(context.exports.pendingExternalQr(),'');
assert.equal(clean,'/agency/agenda?tour=test');
const main=fs.readFileSync(new URL('../src/main.tsx',import.meta.url),'utf8');
assert.ok(main.indexOf('captureExternalQr();')<main.indexOf('Sentry.init('));
console.log('PASS QR removed from URL before telemetry; valid token retained only in memory; invalid token rejected.');
